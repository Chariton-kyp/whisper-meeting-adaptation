"""Create the fixed ID lists in splits/ and check partition disjointness.

- ami_sdm_train_order.txt: seeded permutation of SDM train utterances with non-empty text. The
  training subset of size N is the first N lines, so the pilot uses a prefix of the final subset.
- ami_sdm_dev_select.txt: 2,000 SDM validation utterances, proportionally stratified by meeting.
- earnings22_test_2000.txt: 2,000 Earnings-22 chunked test segments from the 4 fixed shards,
  proportionally stratified by file_id.
- README.md: sizes and the train/validation/test meeting and speaker overlap check.

Usage: uv run python scripts/make_splits.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from meeting_asr.data import load_manifest
from meeting_asr.sources import EARNINGS22, load_source_manifest

SEED = 0
OUT = Path("splits")


def stratified_sample(df: pd.DataFrame, group: str, n: int, seed: int) -> pd.DataFrame:
    """Proportional allocation per group (largest remainder), then a seeded sample within each."""
    rng = np.random.default_rng(seed)
    sizes = df.groupby(group).size()
    quota = sizes / sizes.sum() * n
    alloc = np.floor(quota).astype(int)
    for g in (quota - alloc).sort_values(ascending=False).index[: n - alloc.sum()]:
        alloc[g] += 1
    parts = []
    for g, k in alloc.items():
        rows = df[df[group] == g]
        parts.append(rows.iloc[rng.choice(len(rows), size=k, replace=False)])
    return pd.concat(parts).sort_values(df.columns[0])


def main() -> None:
    OUT.mkdir(exist_ok=True)
    train = load_manifest("sdm", "train")
    dev = load_manifest("sdm", "validation")
    test = load_manifest("sdm", "test")

    usable = train[train["text"].str.strip() != ""]
    order = usable["audio_id"].sort_values().sample(frac=1.0, random_state=SEED)
    (OUT / "ami_sdm_train_order.txt").write_text("\n".join(order) + "\n", encoding="utf-8")

    dev_sel = stratified_sample(dev[["audio_id", "meeting_id"]], "meeting_id", 2000, SEED)
    (OUT / "ami_sdm_dev_select.txt").write_text("\n".join(dev_sel["audio_id"]) + "\n", encoding="utf-8")

    e22 = load_source_manifest(EARNINGS22)
    e22_sel = stratified_sample(e22[["audio_id", "meeting_id"]], "meeting_id", 2000, SEED)
    (OUT / "earnings22_test_2000.txt").write_text("\n".join(e22_sel["audio_id"]) + "\n", encoding="utf-8")

    def overlap(a: pd.DataFrame, b: pd.DataFrame, col: str) -> int:
        return len(set(a[col]) & set(b[col]))

    lines = [
        "# Fixed splits",
        "",
        "Generated by `scripts/make_splits.py` (seed 0) from `edinburghcstr/ami` @ 46f28f2 and",
        "`distil-whisper/earnings22` @ 0a034f9 (chunked test shards 0, 12, 25, 37).",
        "",
        "| File | Lines | Description |",
        "|---|---:|---|",
        f"| `ami_sdm_train_order.txt` | {len(order)} | seeded permutation of SDM train (non-empty text); subset = first N |",
        f"| `ami_sdm_dev_select.txt` | {len(dev_sel)} | SDM validation, stratified by meeting ({dev_sel['meeting_id'].nunique()} meetings) |",
        f"| `earnings22_test_2000.txt` | {len(e22_sel)} | stratified by call ({e22_sel['meeting_id'].nunique()} calls of {e22['meeting_id'].nunique()}) |",
        "",
        "## Partition check (SDM)",
        "",
        f"- Utterances: train {len(train)} ({(train['text'].str.strip() == '').sum()} with empty text), "
        f"validation {len(dev)}, test {len(test)}",
        f"- Meetings: train {train['meeting_id'].nunique()}, validation {dev['meeting_id'].nunique()}, "
        f"test {test['meeting_id'].nunique()}",
        f"- Speakers: train {train['speaker_id'].nunique()}, validation {dev['speaker_id'].nunique()}, "
        f"test {test['speaker_id'].nunique()}",
        f"- Shared meetings: train-validation {overlap(train, dev, 'meeting_id')}, "
        f"train-test {overlap(train, test, 'meeting_id')}, validation-test {overlap(dev, test, 'meeting_id')}",
        f"- Shared speakers: train-validation {overlap(train, dev, 'speaker_id')}, "
        f"train-test {overlap(train, test, 'speaker_id')}, validation-test {overlap(dev, test, 'speaker_id')}",
        f"- Train hours: {train['duration'].sum() / 3600:.1f}",
        "",
    ]
    (OUT / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
